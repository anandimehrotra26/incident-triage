"""Summarise errors and abstentions from results/errors_*.csv -> results/ERROR_SUMMARY.md

Run after `python -m triage.evaluate`.
"""
from pathlib import Path

import pandas as pd

RESULTS = Path(__file__).resolve().parent.parent / "results"
APPROACHES = ["A_rules_baseline", "B_tfidf_logreg", "C_tfidf_logreg_plus_rule_features", "C+_with_urgent_safety_net"]


def summarise(e):
    n = len(e)
    abst = e[e.abstained == 1]
    auto = e[e.abstained == 0]
    wrong_auto = auto[auto.pred_category != auto.true_category]
    would_be_wrong = (abst.pred_category != abst.true_category).sum()
    out = {
        "n": n,
        "abstained": len(abst),
        "abstained_truly_unclear": int((abst.true_category == "unclear_other").sum()),
        "abstentions_that_were_necessary (argmax would have been wrong)": int(would_be_wrong),
        "abstentions_that_were_unnecessary (argmax was right)": int(len(abst) - would_be_wrong),
        "auto_routed": len(auto),
        "auto_routed_wrong_team": len(wrong_auto),
        "...of_which_caused_by_injected_label_noise": int(wrong_auto.label_noise_injected.sum()),
        "...of_which_safety_critical_true_category": int(wrong_auto.true_category.isin(["accident_injury", "hazmat_spill", "theft_security"]).sum()),
        "urgent_in_test": int(e.true_urgent.sum()),
        "urgent_not_flagged_urgent": int(((e.true_urgent == 1) & (e.pred_urgent == 0)).sum()),
        "urgent_not_flagged_and_auto_routed": int(((e.true_urgent == 1) & (e.pred_urgent == 0) & (e.abstained == 0)).sum()),
        "false_urgent_flags": int(((e.true_urgent == 0) & (e.pred_urgent == 1)).sum()),
        "share_of_hard_among_errors_or_abstained": round(float(e[(e.cost > 0)].hard.mean()), 2) if (e.cost > 0).any() else 0,
        "share_of_hard_overall": round(float(e.hard.mean()), 2),
    }
    return out, wrong_auto


def main():
    L = ["# Error summary (auto-generated by `python -m triage.error_analysis`, seed-42 test sets)\n"]
    for mode in ("random", "template"):
        L.append(f"\n## {mode} regime\n")
        for a in APPROACHES:
            e = pd.read_csv(RESULTS / f"errors_{mode}_{a}.csv")
            s, wrong = summarise(e)
            L.append(f"### {a}\n")
            for k, v in s.items():
                L.append(f"- {k}: {v}")
            if len(wrong):
                pairs = wrong.groupby(["true_category", "pred_category"]).size().sort_values(ascending=False).head(6)
                L.append("- top auto-routed confusions (true -> predicted): " + "; ".join(f"{t}->{p} x{n}" for (t, p), n in pairs.items()))
            ab = e[e.abstained == 1].true_category.value_counts()
            L.append("- abstentions by true category: " + ", ".join(f"{c} {n}" for c, n in ab.items()))
            mu = e[(e.true_urgent == 1) & (e.pred_urgent == 0)]
            if len(mu):
                L.append("- urgent reports NOT flagged urgent:")
                for t in mu.itertuples():
                    L.append(f"    - [{t.true_category}{', sent to human' if t.abstained else ', auto-routed'}] {t.text}")
            L.append("")
    (RESULTS / "ERROR_SUMMARY.md").write_text("\n".join(L))
    print("wrote results/ERROR_SUMMARY.md")


if __name__ == "__main__":
    main()
